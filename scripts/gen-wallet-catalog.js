/* Writes supabase/wallet_catalog.sql from the shop (src/shop.js): the prices the server charges.
 * Usage: node scripts/gen-wallet-catalog.js          (tests/wallet_catalog.test.js fails when the file is out of date)
 * The file only adds and updates rows; an item is never removed, so a player who owns it keeps it. */
const fs = require('fs');
const path = require('path');
const Shop = require('../src/shop.js');

function build() {
  const rows = Shop.ITEMS.map((i) => `  ('${i.id}', ${i.price})`).join(',\n');
  return '-- GENERATED by scripts/gen-wallet-catalog.js from src/shop.js. Do not edit: change the shop, then run the script.\n' +
    '-- The prices the server charges (gs_wallet_buy). Run after wallet.sql, and again whenever a price or an item changes.\n' +
    '-- A price change applies to new purchases only. Rows are never deleted, so what a player owns stays valid.\n' +
    'begin;\n' +
    'insert into public.wallet_catalog (id, price) values\n' + rows + '\n' +
    'on conflict (id) do update set price = excluded.price;\n' +
    'commit;\n';
}
if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, '..', 'supabase', 'wallet_catalog.sql'), build());
  console.log('wrote supabase/wallet_catalog.sql (' + Shop.ITEMS.length + ' items)');
}
module.exports = { build };
